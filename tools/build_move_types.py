"""Generates route_data/move_types.py: elemental type of every move that can appear in a battle.

Types come from @smogon/calc (generation 3), installed in damage_calculator/node_modules.
Usage:  python tools/build_move_types.py
"""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import battle_simulator as bs  # noqa: E402
from route_data.trainers import TRAINERS  # noqa: E402

NODE_SCRIPT = """
import { Generations } from "@smogon/calc";
const out = {};
for (const m of Generations.get(3).moves) out[m.id] = m.type.toLowerCase();
console.log(JSON.stringify(out));
"""


def used_moves() -> set:
    moves = {"tackle"}
    for entry in bs.dataset["pkdex"].values():
        moves.update(entry["moves"])
    for trainer in TRAINERS.values():
        teams = trainer.values() if isinstance(trainer, dict) else [trainer]
        for team in teams:
            for pkm in team:
                moves.update(pkm["moves"])
    return moves


def main():
    sys.stdout.reconfigure(encoding="utf-8")
    raw = subprocess.run(["node", "--input-type=module", "-e", NODE_SCRIPT], cwd=ROOT / "damage_calculator",
                         capture_output=True, text=True, check=True).stdout
    smogon = json.loads(raw)
    types, missing = {}, []
    for move in sorted(used_moves()):
        key = move.replace("-", "").replace(" ", "").lower()
        if key in smogon:
            types[move] = smogon[key]
        else:
            missing.append(move)
    lines = ['"""Elemental type of each move (generated by tools/build_move_types.py from @smogon/calc, gen 3)."""',
             "", "MOVE_TYPES = {"]
    lines += [f'    "{move}": "{t}",' for move, t in types.items()]
    lines += ["}", ""]
    (ROOT / "route_data" / "move_types.py").write_text("\n".join(lines), encoding="utf-8")
    print(f"{len(types)} movimientos con tipo escritos en route_data/move_types.py")
    if missing:
        print(f"Sin tipo ({len(missing)}): {missing}")


if __name__ == "__main__":
    main()
